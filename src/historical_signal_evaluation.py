"""Descriptive historical evaluation for Kairon's existing signals.

This module evaluates what happened after historical classifications. It reuses
``strategy_rules.generate_basic_signal`` and never creates a second signal
decision or changes the existing strategy logic.
"""

from __future__ import annotations

from datetime import datetime
from statistics import median
from typing import Iterable

from market_condition import SIGNAL_ORDER
from strategy_rules import generate_basic_signal


FORWARD_HORIZONS = (1, 3, 7)
MINIMUM_SIGNAL_CANDLES = 22
SAMPLE_SIZE_VERY_SMALL_MAX = 9
SAMPLE_SIZE_SMALL_MAX = 29
SAMPLE_SIZE_MODERATE_MAX = 99


def _horizon_key(horizon: int) -> str:
    """Return the public dictionary key for a forward horizon."""
    return f"{horizon}d"


def _format_candle_date(candle: dict, fallback_index: int = 0) -> str:
    """Return a readable date from common candle fields."""
    if candle.get("date") is not None:
        return str(candle["date"])

    if candle.get("timestamp") is not None:
        timestamp = candle["timestamp"]
        if isinstance(timestamp, (int, float)):
            timestamp_seconds = (
                timestamp / 1000 if timestamp > 10_000_000_000 else timestamp
            )
            return datetime.fromtimestamp(timestamp_seconds).date().isoformat()
        return str(timestamp)

    if candle.get("open_time") is not None:
        timestamp_seconds = candle["open_time"] / 1000
        return datetime.fromtimestamp(timestamp_seconds).date().isoformat()

    return f"index-{fallback_index}"


def _format_period(dates: list[str]) -> str:
    """Return an inclusive period string from ISO-like date values."""
    if not dates:
        return "unavailable"
    return f"{min(dates)} to {max(dates)}"


def get_market_data_period(candles_by_asset: dict[str, list[dict]]) -> str:
    """Return the earliest-to-latest period in the raw candle dataset."""
    dates = [
        _format_candle_date(candle, index)
        for candles in candles_by_asset.values()
        for index, candle in enumerate(candles)
    ]
    return _format_period(dates)


def get_valid_signal_evaluation_period(occurrences: list[dict]) -> str:
    """Return the period in which valid historical signals were generated."""
    dates = [
        str(occurrence["date"])
        for occurrence in occurrences
        if occurrence.get("date") is not None
    ]
    return _format_period(dates)


def _validate_horizons(horizons: Iterable[int]) -> tuple[int, ...]:
    """Validate and normalize requested forward horizons."""
    normalized = tuple(horizons)
    if not normalized or any(horizon <= 0 for horizon in normalized):
        raise ValueError("Forward horizons must contain positive integers.")
    if len(set(normalized)) != len(normalized):
        raise ValueError("Forward horizons must not contain duplicates.")
    return normalized


def calculate_forward_return(
    prices: list[float],
    index: int,
    horizon: int,
) -> float | None:
    """Calculate a simple forward percentage return when future data exists."""
    if horizon <= 0 or index < 0 or index >= len(prices):
        return None

    future_index = index + horizon
    if future_index >= len(prices):
        return None

    signal_day_price = prices[index]
    if signal_day_price == 0:
        return None

    future_price = prices[future_index]
    return ((future_price - signal_day_price) / signal_day_price) * 100


def evaluate_signal_occurrence(
    symbol: str,
    candles: list[dict],
    index: int,
    horizons: Iterable[int] = FORWARD_HORIZONS,
) -> dict:
    """Evaluate one historical signal occurrence and its future returns.

    The signal is generated by passing only candles available at ``index`` to
    the existing strategy function. Future candles are used only for return
    measurement and can never influence the classification.
    """
    normalized_horizons = _validate_horizons(horizons)
    if index < MINIMUM_SIGNAL_CANDLES - 1 or index >= len(candles):
        raise ValueError(
            f"Signal index must be between {MINIMUM_SIGNAL_CANDLES - 1} and "
            f"{len(candles) - 1}."
        )

    closes = [candle["close"] for candle in candles]
    signal_result = generate_basic_signal(symbol, closes[: index + 1])
    prices = closes

    occurrence = {
        "asset": signal_result["symbol"],
        "date": _format_candle_date(candles[index], index),
        "price": signal_result["current_price"],
        "signal": signal_result["signal"],
        "sma_7": signal_result["sma_7"],
        "sma_21": signal_result["sma_21"],
        "rsi_14": signal_result["rsi_14"],
        "change_7d": signal_result["change_7d"],
    }

    for horizon in normalized_horizons:
        occurrence[f"forward_return_{_horizon_key(horizon)}"] = calculate_forward_return(
            prices,
            index,
            horizon,
        )

    return occurrence


def collect_historical_signal_occurrences(
    symbol: str,
    candles: list[dict],
    horizons: Iterable[int] = FORWARD_HORIZONS,
) -> list[dict]:
    """Collect all signal occurrences available in one asset's candle history."""
    normalized_horizons = _validate_horizons(horizons)
    if len(candles) < MINIMUM_SIGNAL_CANDLES:
        return []

    return [
        evaluate_signal_occurrence(symbol, candles, index, normalized_horizons)
        for index in range(MINIMUM_SIGNAL_CANDLES - 1, len(candles))
    ]


def get_sample_size_note(sample_size: int) -> str:
    """Return a transparent communication note for a sample size."""
    if sample_size == 0:
        return "No historical observations are available for this signal and horizon."

    if sample_size <= SAMPLE_SIZE_VERY_SMALL_MAX:
        return (
            "Very small historical sample. Results are insufficient for meaningful "
            "interpretation."
        )

    if sample_size <= SAMPLE_SIZE_SMALL_MAX:
        return "Small historical sample. Interpret descriptive results cautiously."

    if sample_size <= SAMPLE_SIZE_MODERATE_MAX:
        return (
            "Moderate raw historical sample. Results remain descriptive, and "
            "overlapping observations may reduce the effective amount of "
            "independent information."
        )

    return (
        "Larger raw historical sample. Forward-return windows and cross-asset "
        "observations may not be independent, so the count should not be "
        "interpreted as an effective statistical sample size. Results remain "
        "descriptive."
    )


def _empty_return_summary(sample_size: int = 0) -> dict:
    """Build a return summary without fabricating missing values."""
    return {
        "observations": sample_size,
        "average_return": None,
        "median_return": None,
        "positive_return_percentage": None,
        "best_observed_return": None,
        "worst_observed_return": None,
        "sample_size_note": get_sample_size_note(sample_size),
    }


def _summarize_returns(returns: list[float]) -> dict:
    """Calculate descriptive statistics for valid forward returns."""
    if not returns:
        return _empty_return_summary()

    positive_count = sum(return_value > 0 for return_value in returns)
    return {
        "observations": len(returns),
        "average_return": sum(returns) / len(returns),
        "median_return": median(returns),
        "positive_return_percentage": (positive_count / len(returns)) * 100,
        "best_observed_return": max(returns),
        "worst_observed_return": min(returns),
        "sample_size_note": get_sample_size_note(len(returns)),
    }


def _summarize_for_signal(
    occurrences: list[dict],
    signal: str,
    horizons: tuple[int, ...],
) -> dict:
    """Summarize all requested horizons for one signal."""
    signal_occurrences = [
        occurrence for occurrence in occurrences if occurrence.get("signal") == signal
    ]
    summary = {
        "total_occurrences": len(signal_occurrences),
    }

    for horizon in horizons:
        key = f"forward_return_{_horizon_key(horizon)}"
        returns = [
            occurrence.get(key)
            for occurrence in signal_occurrences
            if occurrence.get(key) is not None
        ]
        summary[_horizon_key(horizon)] = _summarize_returns(returns)

    return summary


def summarize_signal_performance(
    occurrences: list[dict],
    horizons: Iterable[int] = FORWARD_HORIZONS,
) -> dict:
    """Summarize pooled historical performance for every Kairon signal."""
    normalized_horizons = _validate_horizons(horizons)
    return {
        signal: _summarize_for_signal(occurrences, signal, normalized_horizons)
        for signal in SIGNAL_ORDER
    }


def summarize_asset_signal_performance(
    occurrences: list[dict],
    horizons: Iterable[int] = FORWARD_HORIZONS,
) -> dict:
    """Summarize historical performance separately for each asset and signal."""
    normalized_horizons = _validate_horizons(horizons)
    assets = sorted(
        {occurrence.get("asset", "UNKNOWN") for occurrence in occurrences}
    )

    return {
        asset: {
            signal: _summarize_for_signal(
                [
                    occurrence
                    for occurrence in occurrences
                    if occurrence.get("asset") == asset
                ],
                signal,
                normalized_horizons,
            )
            for signal in SIGNAL_ORDER
        }
        for asset in assets
    }


def evaluate_historical_signals(
    candles_by_asset: dict[str, list[dict]],
    horizons: Iterable[int] = FORWARD_HORIZONS,
) -> dict:
    """Evaluate existing Kairon signals across multiple asset histories."""
    normalized_horizons = _validate_horizons(horizons)
    occurrences = []

    for symbol, candles in candles_by_asset.items():
        occurrences.extend(
            collect_historical_signal_occurrences(symbol, candles, normalized_horizons)
        )

    signal_performance = summarize_signal_performance(occurrences, normalized_horizons)
    asset_signal_performance = summarize_asset_signal_performance(
        occurrences,
        normalized_horizons,
    )
    signal_occurrences = {
        signal: sum(
            1 for occurrence in occurrences if occurrence.get("signal") == signal
        )
        for signal in SIGNAL_ORDER
    }
    market_data_period = get_market_data_period(candles_by_asset)
    valid_signal_evaluation_period = get_valid_signal_evaluation_period(occurrences)

    return {
        "assets_evaluated": sorted(symbol.upper() for symbol in candles_by_asset),
        "market_data_period": market_data_period,
        "valid_signal_evaluation_period": valid_signal_evaluation_period,
        # Keep the v0.4 field available for callers that used the original report.
        "historical_period": market_data_period,
        "total_occurrences": len(occurrences),
        "signal_occurrences": signal_occurrences,
        "forward_horizons": normalized_horizons,
        "occurrences": occurrences,
        "signal_performance": signal_performance,
        "asset_signal_performance": asset_signal_performance,
    }
